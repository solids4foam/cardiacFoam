"""Continuum 1D-3D junction of the Purkinje-graph and myocardium manufactured solution: Vm3D(x, y, z, t), V1D(x, t), terminal_current_exact, continuum_sampling, continuum_current, terminal_deposition, continuum_junction_source, with the half-ball kernel quadrature.  Generated by coupled_1d3d_mms.py."""

import numpy

# module: coupled_1d3d

PARAMS = {'RADIUS': 0.11, 'R_PVJ': 1.0, 'CHI': 3, 'CM': 2}


def Vm3D(x, y, z, t):
    _ref = numpy.zeros(numpy.broadcast(x, y, z, t).shape)
    return (numpy.sqrt(t + 1)*numpy.cos(numpy.pi*x)*numpy.cos(2*numpy.pi*y)*numpy.cos(3*numpy.pi*z)) + _ref


def V1D(x, t):
    _ref = numpy.zeros(numpy.broadcast(x, t).shape)
    return (numpy.sqrt(t + 1)*numpy.cos(numpy.pi*x)) + _ref


def _nodes(a, b, n):
    """Gauss-Legendre nodes and weights on [a, b]."""
    t, w = numpy.polynomial.legendre.leggauss(n)
    return 0.5 * (b - a) * t + 0.5 * (b + a), 0.5 * (b - a) * w


def _ray_length(direction, centre, radius, box_lo, box_hi):
    """Length of each ray from the centre, cut by the ball and the box."""
    with numpy.errstate(divide="ignore", invalid="ignore"):
        to_hi = numpy.where(direction > 0, (box_hi[:, None] - centre[:, None]) / direction, numpy.inf)
        to_lo = numpy.where(direction < 0, (box_lo[:, None] - centre[:, None]) / direction, numpy.inf)
    return numpy.minimum(radius, numpy.minimum(to_hi, to_lo).min(axis=0))


def half_ball_kernel_integral(f, centre, radius, box_lo, box_hi, n):
    """Integrals of w*f and w over the ball intersected with the box.

    w = max(0, 1 - |x - centre| / radius).  Spherical coordinates about the
    centre with the polar axis along the first coordinate: the polar cosine
    mu is split where the first-axis faces start to cut the ball, so a ball
    centred on a first-axis face (a half ball) is integrated with smooth
    integrands on every piece; n points per direction and per piece.  Cuts by
    the other faces enter through the ray length and converge algebraically.
    """
    centre = numpy.asarray(centre, dtype=float)
    box_lo = numpy.asarray(box_lo, dtype=float)
    box_hi = numpy.asarray(box_hi, dtype=float)
    breaks = {-1.0, 1.0}
    for d in (centre[0] - box_lo[0], box_hi[0] - centre[0]):
        if 0.0 <= d < radius:
            breaks.update((d / radius, -d / radius))
    breaks = sorted(breaks)

    phi, w_phi = _nodes(0.0, 2.0 * numpy.pi, n)
    t_r, w_r = numpy.polynomial.legendre.leggauss(n)
    total_f = 0.0
    total_w = 0.0
    for a, b in zip(breaks[:-1], breaks[1:]):
        if b - a < 1e-14:
            continue
        mu, w_mu = _nodes(a, b, n)
        MU, PHI = numpy.meshgrid(mu, phi, indexing="ij")
        W2 = w_mu[:, None] * w_phi[None, :]
        sin_t = numpy.sqrt(numpy.maximum(0.0, 1.0 - MU**2))
        direction = numpy.array([MU, sin_t * numpy.cos(PHI), sin_t * numpy.sin(PHI)]).reshape(3, -1)
        length = _ray_length(direction, centre, radius, box_lo, box_hi)
        r = 0.5 * length[None, :] * (t_r[:, None] + 1.0)
        wr = 0.5 * length[None, :] * w_r[:, None]
        pts = centre[:, None, None] + direction[:, None, :] * r[None]
        kernel = numpy.maximum(0.0, 1.0 - r / radius)
        weight = (W2.reshape(1, -1) * wr * r**2) * kernel
        total_f += float(numpy.sum(weight * f(pts)))
        total_w += float(numpy.sum(weight))
    return total_f, total_w


TERMINALS = ((0.0, 1.0/6.0, 1.0/3.0), (1.0, 1.0/6.0, 1.0/3.0))
RADIUS = 0.11
CUBE_LO = numpy.zeros(3)
CUBE_HI = numpy.ones(3)
MAX_RADIUS = 1.0/6.0


def require_half_ball(radius):
    """Reject a radius outside (0, MAX_RADIUS]: the half-ball mass would not hold."""
    if not 0.0 < radius <= MAX_RADIUS:
        raise ValueError("kernel radius %r outside (0, %.6g]: beyond it the ball about a "
                         "terminal meets a second cube face and its mass is not pi r^3/6"
                         % (radius, MAX_RADIUS))


def terminal_current_exact(t, R_pvj=1.0):
    """Point-value terminal currents +-(3/2) sqrt(1 + t) / R_pvj."""
    s = 1.5*numpy.sqrt(1.0 + t)/R_pvj
    return (float(s), float(-s))


def continuum_sampling(k, t, radius=RADIUS, n=32):
    """Vbar_k = int w V_m / int w over the half ball at terminal k."""
    require_half_ball(radius)
    num, den = half_ball_kernel_integral(
        lambda p: Vm3D(p[0], p[1], p[2], t), TERMINALS[k], radius, CUBE_LO, CUBE_HI, n)
    return num/den


def continuum_current(k, t, radius=RADIUS, n=32, R_pvj=1.0):
    """I_pvj,k = (V_1D,k - Vbar_k) / R_pvj."""
    return (float(V1D(TERMINALS[k][0], t)) - continuum_sampling(k, t, radius, n))/R_pvj


def _kernel(k, points, radius):
    r = numpy.linalg.norm(numpy.asarray(points, dtype=float) - numpy.asarray(TERMINALS[k]), axis=-1)
    return numpy.maximum(0.0, 1.0 - r/radius)


def terminal_deposition(k, points, t, radius=RADIUS, n=32, R_pvj=1.0):
    """I_pvj,k w_k / int w_k at points of shape (N, 3)."""
    require_half_ball(radius)
    mass = numpy.pi*radius**3/6.0
    return continuum_current(k, t, radius, n, R_pvj)*_kernel(k, points, radius)/mass


def continuum_junction_source(points, t, radius=RADIUS, n=32, R_pvj=1.0):
    """S_pvj at points of shape (N, 3): the sum of the terminal depositions."""
    pts = numpy.atleast_2d(numpy.asarray(points, dtype=float))
    return sum(terminal_deposition(k, pts, t, radius, n, R_pvj) for k in range(len(TERMINALS)))
