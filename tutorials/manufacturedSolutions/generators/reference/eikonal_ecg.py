def template_derivative_single_event(s, duration, rise):
    _ref = numpy.zeros(numpy.broadcast(s, duration, rise).shape)
    _t0 = numpy.arctanh(4/5)/rise
    _t1 = 2*_t0
    _t2 = numpy.tanh(_t1*s)
    _t3 = numpy.tanh(_t1*(-duration + s))
    return ((1/2)*_t0*((1 - _t2**2)*(1 - _t3) - (1 - _t3**2)*(_t2 + 1))) + _ref


def template_derivative_sine(s):
    _ref = numpy.zeros(numpy.broadcast(s).shape)
    _t0 = 2*numpy.pi
    return (_t0*numpy.cos(_t0*s)) + _ref


