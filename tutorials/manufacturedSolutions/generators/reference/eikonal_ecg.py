    _t0 = -ex + x
    _t1 = -ey + y
    _t2 = _t0**2 + _t1**2
    _t3 = numpy.exp(x + y)
    _t4 = numpy.arctanh(4/5)/rise
    _t5 = 2*_t4
    _t6 = numpy.tanh(_t5*(-_t3 + t))
    _t7 = numpy.tanh(_t5*(-_t3 - duration + t))
    _t8 = (1/2)*_t3*_t4*((1 - _t6**2)*(1 - _t7) - (1 - _t7**2)*(_t6 + 1))
    _t9 = _t8*sxy
    return (numpy.select([numpy.less_equal(_t2, 1.0e-300),True], [0,(_t0*(-_t8*sxx - _t9) + _t1*(-_t8*syy - _t9))/_t2**(3/2)], default=numpy.nan)) + _ref


