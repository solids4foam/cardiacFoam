    _t2 = numpy.exp(x)
    _t3 = numpy.arctanh(4/5)/rise
    _t4 = 2*_t3
    _t5 = numpy.tanh(_t4*(-_t2 + t))
    _t6 = numpy.tanh(_t4*(-_t2 - duration + t))
    return (numpy.select([numpy.less_equal(_t1, 1.0e-300),True], [0,(1/2)*_t2*_t3*sxx*((1 - _t5**2)*(1 - _t6) - (1 - _t6**2)*(_t5 + 1))/(_t0*_t1)], default=numpy.nan)) + _ref


