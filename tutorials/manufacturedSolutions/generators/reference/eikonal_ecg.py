    _t5 = numpy.pi*_t4*numpy.cos(numpy.pi*(-_t4 + 2*t))
    _t6 = _t5*sxy
    _t7 = _t5*sxz
    _t8 = _t5*syz
    return (numpy.select([numpy.less_equal(_t3, 1.0e-300),True], [0,(_t0*(-_t5*sxx - _t6 - _t7) + _t1*(-_t5*syy - _t6 - _t8) + _t2*(-_t5*szz - _t7 - _t8))/_t3**(3/2)], default=numpy.nan)) + _ref


