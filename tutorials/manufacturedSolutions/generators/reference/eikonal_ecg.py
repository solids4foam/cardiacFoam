def integrand_d3_single_event(x, y, z, t, ex, ey, ez, sxx, sxy, sxz, syy, syz, szz, duration, rise):
    _ref = numpy.zeros(numpy.broadcast(x, y, z, t, ex, ey, ez, sxx, sxy, sxz, syy, syz, szz, duration, rise).shape)
