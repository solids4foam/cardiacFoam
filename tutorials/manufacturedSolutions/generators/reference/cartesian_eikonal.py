"""Manufactured eikonal field psi = exp(k_d . x) on the unit cube: tau_d<d>, grad_tau_d<d>(x, y, z) and source_d<d>(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz); source(d, point, sigma, c0) checks K_M > 0.  Generated by cartesian_eikonal_mms.py."""

import numpy

# module: cartesian_eikonal

PARAMS = {'SIGMA_ROTATED': [0.106875, -0.0084931, -0.022561, 0.116682, -0.0130256, 0.0398782], 'SIGMA_AXIS': [0.111453302, 0.0, 0.0, 0.12158542, 0.0, 0.030396355], 'CHI': 3.0, 'CM': 2.0, 'KM_MIN': 1e-300}


def tau_d1(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    return (numpy.exp(x)) + _ref


def grad_tau_d1(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    _out = numpy.stack([(numpy.exp(x)) + _ref, (0) + _ref, (0) + _ref])
    return _out.reshape((3,) + numpy.shape(_ref))


def source_d1(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz):
    _ref = numpy.zeros(numpy.broadcast(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz).shape)
    return ((c0*numpy.sqrt(sxx)/(numpy.sqrt(chi)*numpy.sqrt(cm)) - sxx/(chi*cm))*numpy.exp(x) - 1) + _ref


def tau_d2(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    return (numpy.exp(x + y)) + _ref


def grad_tau_d2(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    _t0 = numpy.exp(x + y)
    _out = numpy.stack([(_t0) + _ref, (_t0) + _ref, (0) + _ref])
    return _out.reshape((3,) + numpy.shape(_ref))


def source_d2(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz):
    _ref = numpy.zeros(numpy.broadcast(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz).shape)
    _t0 = 1/(chi*cm)
    _t1 = _t0*sxx + 2*_t0*sxy + _t0*syy
    return ((numpy.sqrt(_t1)*c0 - _t1)*numpy.exp(x + y) - 1) + _ref


def tau_d3(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    return (numpy.exp(x + y + z)) + _ref


def grad_tau_d3(x, y, z):
    _ref = numpy.zeros(numpy.broadcast(x, y, z).shape)
    _t0 = numpy.exp(x + y + z)
    _out = numpy.stack([(_t0) + _ref, (_t0) + _ref, (_t0) + _ref])
    return _out.reshape((3,) + numpy.shape(_ref))


def source_d3(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz):
    _ref = numpy.zeros(numpy.broadcast(x, y, z, c0, chi, cm, sxx, sxy, sxz, syy, syz, szz).shape)
    _t0 = 1/(chi*cm)
    _t1 = 2*_t0
    _t2 = _t0*sxx + _t0*syy + _t0*szz + _t1*sxy + _t1*sxz + _t1*syz
    return ((numpy.sqrt(_t2)*c0 - _t2)*numpy.exp(x + y + z) - 1) + _ref


KM_MIN = 1e-300


def _sigma_entries(sigma):
    s = numpy.asarray(sigma, dtype=float)
    if s.shape == (3, 3):
        return (s[0, 0], s[0, 1], s[0, 2], s[1, 1], s[1, 2], s[2, 2])
    return tuple(float(v) for v in s)


def k_metric(d, sigma, chi=3.0, cm=2.0):
    """K_M = k_d . M k_d with M = sigma/(chi cm); raises when not positive."""
    sxx, sxy, sxz, syy, syz, szz = _sigma_entries(sigma)
    if d == 1:
        km = sxx
    elif d == 2:
        km = sxx + 2.0*sxy + syy
    else:
        km = sxx + syy + szz + 2.0*(sxy + sxz + syz)
    km = km/(chi*cm)
    if not km > KM_MIN:
        raise ValueError("K_M must exceed %g, got %r" % (KM_MIN, km))
    return km


def source(d, point, sigma, c0, chi=3.0, cm=2.0):
    """S_psi at point (x, y, z); raises when K_M <= 1e-300."""
    k_metric(d, sigma, chi, cm)
    f = globals()["source_d%d" % d]
    return f(*point, c0, chi, cm, *_sigma_entries(sigma))
