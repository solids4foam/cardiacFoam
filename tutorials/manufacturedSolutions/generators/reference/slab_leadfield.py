PARAMS = {'K': 0.7071067811862892, 'ALPHA': 0.01, 'SIGMA_SLAB': 0.0230827345, 'LAYERS': {'xLeft': -0.5, 'xRight': 1.5, 'sigmaOuterLeft': 0.02, 'sigmaInnerLeft': 0.1, 'sigmaHeart': 0.53814414652, 'sigmaInnerRight': 0.1, 'sigmaOuterRight': 0.02}, 'LAYER_NAMES': ['xLeft', 'xRight', 'sigmaOuterLeft', 'sigmaInnerLeft', 'sigmaHeart', 'sigmaInnerRight', 'sigmaOuterRight'], 'PHI_REF_POINT': [-0.9013, 0.0437, 0.0437], 'PHI_REF_VALUE': 0.0}


def Vm(x, t):
    _ref = numpy.zeros(numpy.broadcast(x, t).shape)
    return (numpy.sqrt(t + 1)*numpy.cos(numpy.pi*x)) + _ref


def phi_slab(x, t, k):
    _ref = numpy.zeros(numpy.broadcast(x, t, k).shape)
    _t0 = numpy.sqrt(t + 1)
    _t1 = _t0*k
    return (numpy.select([numpy.less_equal(x, 0),numpy.less_equal(x, 1),True], [0,_t0*k - _t1*numpy.cos(numpy.pi*x),2*_t1], default=numpy.nan)) + _ref


def resistance(x, xLeft, xRight, sigmaOuterLeft, sigmaInnerLeft, sigmaHeart, sigmaInnerRight, sigmaOuterRight):
    _ref = numpy.zeros(numpy.broadcast(x, xLeft, xRight, sigmaOuterLeft, sigmaInnerLeft, sigmaHeart, sigmaInnerRight, sigmaOuterRight).shape)
    _t0 = sigmaInnerLeft**(-1.0)
    _t1 = sigmaHeart**(-1.0)
    _t2 = sigmaInnerRight**(-1.0)
    return (numpy.select([numpy.less_equal(x, xLeft),numpy.less_equal(x, 0),numpy.less_equal(x, 1),numpy.less_equal(x, xRight),True], [_t0*xLeft + (x - xLeft)/sigmaOuterLeft,_t0*x,_t1*x,_t1 + _t2*(x - 1),_t1 + _t2*(xRight - 1) + (x - xRight)/sigmaOuterRight], default=numpy.nan)) + _ref


def phi_layered(x, t, k, alpha, xLeft, xRight, sigmaOuterLeft, sigmaInnerLeft, sigmaHeart, sigmaInnerRight, sigmaOuterRight):
    _ref = numpy.zeros(numpy.broadcast(x, t, k, alpha, xLeft, xRight, sigmaOuterLeft, sigmaInnerLeft, sigmaHeart, sigmaInnerRight, sigmaOuterRight).shape)
    _t0 = numpy.less_equal(x, 0)
    _t1 = numpy.sqrt(t + 1)
    _t2 = _t1*k
    _t3 = numpy.less_equal(x, 1)
    _t4 = sigmaInnerLeft**(-1.0)
    _t5 = sigmaHeart**(-1.0)
    _t6 = sigmaInnerRight**(-1.0)
    return (alpha*numpy.select([numpy.less_equal(x, xLeft),_t0,_t3,numpy.less_equal(x, xRight),True], [_t4*xLeft + (x - xLeft)/sigmaOuterLeft,_t4*x,_t5*x,_t5 + _t6*(x - 1),_t5 + _t6*(xRight - 1) + (x - xRight)/sigmaOuterRight], default=numpy.nan) + numpy.select([_t0,_t3,True], [0,_t1*k - _t2*numpy.cos(numpy.pi*x),2*_t2], default=numpy.nan)) + _ref
