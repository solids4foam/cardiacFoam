inline scalar evaluatePurkinjeVmTemplate(scalar localTime)
{
    if (localTime <= purkinjeVmTimes[0])
    {
        return purkinjeVmValues[0];
    }
    if (localTime >= purkinjeVmTimes[numPurkinjeVmSamples - 1])
    {
        return purkinjeVmValues[numPurkinjeVmSamples - 1];
    }

    // Binary search or simply linear search, but since it's 1000 points evenly spaced,
    // we can optimize it or just use upper_bound. Let's just do a simple upper_bound lookup.
    // For simplicity, since dT = 0.001, idx = floor(localTime / 0.001).
    label idx = localTime * 1000.0;
    if (idx < 0) idx = 0;
    if (idx >= numPurkinjeVmSamples - 1) idx = numPurkinjeVmSamples - 2;

    scalar t0 = purkinjeVmTimes[idx];
    scalar t1 = purkinjeVmTimes[idx + 1];
    scalar v0 = purkinjeVmValues[idx];
    scalar v1 = purkinjeVmValues[idx + 1];

    if (localTime > t1 && idx < numPurkinjeVmSamples - 2)
    {
        idx++;
        t0 = purkinjeVmTimes[idx];
        t1 = purkinjeVmTimes[idx + 1];
        v0 = purkinjeVmValues[idx];
        v1 = purkinjeVmValues[idx + 1];
    }

    scalar f = (localTime - t0) / (t1 - t0 + 1e-12);
    return v0 + f * (v1 - v0);
}

